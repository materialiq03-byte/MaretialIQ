const lit = (v) => {
  if (v === null || v === undefined) return 'NULL';
  if (typeof v === 'number') return Number.isInteger(v) ? String(v) : String(v);
  if (typeof v === 'bigint') return String(v);
  return `'${String(v).replace(/'/g, "''")}'`;
};

/**
 * Build the ordered data-step INSERT statements from the frozen SQLite demo
 * (opened READ ONLY by the caller). Verbatim values — nothing invented.
 * Backfills for uom_rule_history / uom_domain_rule_versions mirror migrate.ts
 * v18/v19 SELECT-backfills against the transferred rule rows.
 */
export function buildInsertStatements(sqlite) {
  const statements = [];
  const counts = {};

  const readRows = (plan) => {
    const where = plan.where ? ` WHERE ${plan.where}` : '';
    return sqlite.prepare(`SELECT ${plan.cols.map((c) => `"${c}"`).join(', ')} FROM "${plan.table}"${where} ORDER BY rowid`).all();
  };

  for (const plan of TABLE_PLAN) {
    const rows = readRows(plan);
    counts[plan.table] = rows.length;
    const conflict = ` ON CONFLICT (${TABLE_PKS[plan.table].map((c) => `"${c}"`).join(', ')}) DO NOTHING`;
    for (const row of rows) {
      const values = plan.cols.map((c) => {
        if (plan.kindDefault && c === 'kind' && row[c] === undefined) return plan.kindDefault;
        return lit(row[c]);
      });
      statements.push(
        `INSERT INTO "${plan.table}" (${plan.cols.map((c) => `"${c}"`).join(', ')}) VALUES (${values.join(', ')})${conflict};`
      );
    }
  }

  // v18 backfill: one CREATE history row per transferred domain rule.
  {
    const rules = sqlite.prepare(`SELECT id, cmi_id, from_uom, to_uom, factor, rule_type, created_by, reason, created_at FROM uom_domain_rules`).all();
    counts.uom_rule_history = rules.length;
    for (const d of rules) {
      statements.push(
        `INSERT INTO "uom_rule_history" ("rule_id","cmi_id","from_uom","to_uom","factor","rule_type","previous_status","new_status","action","actor","reason","created_at") VALUES (${[d.id, d.cmi_id, d.from_uom, d.to_uom, d.factor, d.rule_type].map(lit).join(', ')}, NULL, 'PENDING', 'CREATE', ${lit(d.created_by)}, ${lit(d.reason)}, ${lit(d.created_at)}) ON CONFLICT ("id") DO NOTHING;`
      );
    }
  }

  // v19 backfill: version 1 per transferred rule + effective pointer for
  // APPROVED/DISABLED rules only (PENDING rules keep NULL — frozen semantics).
  {
    const rules = sqlite.prepare(`SELECT id, cmi_id, from_uom, to_uom, factor, rule_type, reason, created_by, created_at, status FROM uom_domain_rules`).all();
    counts.uom_domain_rule_versions = rules.length;
    for (const d of rules) {
      statements.push(
        `INSERT INTO "uom_domain_rule_versions" ("rule_id","version_number","cmi_id","from_uom","to_uom","factor","rule_type","amendment_reason","created_by","created_at","supersedes_version_id") VALUES (${[d.id, 1, d.cmi_id, d.from_uom, d.to_uom, d.factor, d.rule_type, d.reason, d.created_by, d.created_at].map(lit).join(', ')}, NULL) ON CONFLICT ("rule_id","version_number") DO NOTHING;`
      );
      if (d.status === 'APPROVED' || d.status === 'DISABLED') {
        statements.push(
          `UPDATE "uom_domain_rules" SET "effective_version_id" = (SELECT v.id FROM "uom_domain_rule_versions" v WHERE v."rule_id" = ${d.id} AND v."version_number" = 1) WHERE "id" = ${d.id} AND "effective_version_id" IS NULL;`
        );
      }
    }
  }

  // Identity sequences continue after the transferred ids.
  const seqTables = ['suppliers', 'procurement_records', 'uom_domain_rules', 'uom_rule_history', 'uom_domain_rule_versions', 'data_imports', 'audit_logs'];
  for (const t of seqTables) {
    statements.push(`SELECT setval(pg_get_serial_sequence('${t}', 'id'), COALESCE((SELECT MAX("id") FROM "${t}"), 0) + 1, false);`);
  }

  return { statements, counts };
}

