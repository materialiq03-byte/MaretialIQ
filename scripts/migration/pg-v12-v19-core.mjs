/**
 * Option A gate ③ — PURE core for the Supabase v12→v19 migration.
 *
 * This module has ZERO side effects on import: no network, no filesystem
 * writes, no database connections. It exposes:
 *
 *   - MIGRATION_SEQUENCE / MIGRATION_NAMES   (v1..v19 bookkeeping)
 *   - buildSchemaStatements(fromVersion)     (versioned DDL, exact order)
 *   - SEED_ROWS_UOM_CONVERSION_RULES         (the 7 v16 SYSTEM_DEFINED rows)
 *   - MANIFEST                               (authoritative insert counts)
 *   - buildInsertStatements(...)             (data step from a SQLite source)
 *   - buildPreflightChecks(...)              (mandatory gate before any write)
 *   - buildVerificationQueries()             (post-migration proof)
 *
 * Execution belongs to gate ④; nothing here connects to any database.
 * DDL text mirrors src/lib/db/migrate.ts v12..v19 (frozen) using the
 * translation rules documented in supabase/README.md (v11 conventions).
 */

