/**
 * Immutability helper (v18/v19): SQLite RAISE(ABORT) triggers become a
 * plpgsql function raising with the trigger's argument text.
 */
const REFUSE_FN = `
CREATE OR REPLACE FUNCTION materialiq_refuse_mutation() RETURNS trigger LANGUAGE plpgsql AS $fn$
BEGIN
  RAISE EXCEPTION '%', TG_ARGV[0];
END $fn$;`;

