/**
 * Pure helpers for the Supabase logical backup generator (gate 3.5 fixes).
 *
 * Zero I/O, zero dependencies, synchronously requirable — unit-tested by
 * tests/pg-migration-plan.test.ts. Two fixes are implemented here:
 *
 *   1. FK-dependency topological table ordering (replaces alphabetical order,
 *      which put FK-referencing sections before their referenced tables and
 *      made `psql -v ON_ERROR_STOP=1` restores fail). Deterministic: Kahn's
 *      algorithm over alphabetical tie-breaks. Cycles are detected and thrown,
 *      never silently reordered unsafely.
 *
 *   2. Identity-column preservation in CREATE TABLE DDL: `bigint GENERATED BY
 *      DEFAULT AS IDENTITY` columns have column_default = NULL, so the old
 *      renderer emitted them as plain NOT NULL bigint and the restored db
 *      lost every identity sequence (setval became a silent no-op).
 */

/**
 * Order tables so every referenced table precedes its referencers.
 *
 * @param {Array<{name: string, references: string[]}>} tables
 *        references = table names (within the same set) this table's FKs point to.
 * @returns {{order: string[], cycles: string[][]}}
 *          order: dependency-safe, deterministic (original-list tie-break).
 *          cycles: non-empty when a dependency cycle makes a safe order impossible.
 */
export function orderTablesByDependency(tables) {
  const byName = new Map(tables.map((t) => [t.name, t]));
  const deps = new Map(); // table -> Set(names it depends on, i.e. must come first)
  for (const t of tables) {
    const set = new Set();
    for (const ref of t.references) {
      if (ref !== t.name && byName.has(ref)) set.add(ref);
    }
    deps.set(t.name, set);
  }

  const order = [];
  const placed = new Set();
  let progressed = true;
  while (order.length < tables.length && progressed) {
    progressed = false;
    // Alphabetical tie-break among the currently "ready" tables for determinism.
    const ready = tables
      .map((t) => t.name)
      .filter((n) => !placed.has(n) && [...deps.get(n)].every((d) => placed.has(d)))
      .sort();
    for (const n of ready) {
      order.push(n);
      placed.add(n);
      progressed = true;
    }
  }

  const cycles = [];
  if (order.length < tables.length) {
    // Whatever remains is cycle-bound; report the components so the caller can
    // fail loudly instead of emitting an unsafe order.
    const remaining = tables.map((t) => t.name).filter((n) => !placed.has(n));
    const inCycle = remaining.filter((n) => [...deps.get(n)].some((d) => !placed.has(d)));
    const seen = new Set();
    for (const start of inCycle) {
      if (seen.has(start)) continue;
      const comp = [];
      const stack = [start];
      while (stack.length) {
        const n = stack.pop();
        if (seen.has(n)) continue;
        seen.add(n);
        comp.push(n);
        for (const d of deps.get(n)) if (!placed.has(d) && !seen.has(d)) stack.push(d);
        for (const [m, ds] of deps) if (ds.has(n) && !placed.has(m) && !seen.has(m)) stack.push(m);
      }
      cycles.push(comp.sort());
    }
  }
  return { order, cycles };
}

/**
 * Render one column definition line exactly as the live schema means it.
 *
 * @param {{column_name:string, data_type:string, is_nullable:string,
 *          column_default:(string|null), character_maximum_length:(number|null),
 *          numeric_precision:(number|null), numeric_scale:(number|null),
 *          is_identity:(string|null), identity_generation:(string|null)}} c
 *        information_schema.columns row.
 * @param {string} identityMode 'preserve' (default) or 'serial' — test hook only;
 *        the generator always passes 'preserve' so live semantics are kept.
 */
export function renderColumnDef(c, identityMode = 'preserve') {
  const id = (s) => `"${s.replace(/"/g, '""')}"`;
  let def = `${id(c.column_name)} ${c.data_type}`;
  if (c.character_maximum_length) def += `(${c.character_maximum_length})`;
  if (c.data_type === 'numeric' && c.numeric_precision) def += `(${c.numeric_precision},${c.numeric_scale ?? 0})`;
  if (c.is_identity === 'YES' && c.identity_generation) {
    if (identityMode === 'preserve') {
      // Exactly the live semantics: BY DEFAULT keeps explicit-id inserts working
      // (setval'd by the backup footer) while DEFAULT inserts generate ids.
      def += ` GENERATED ${c.identity_generation} AS IDENTITY`;
    } else {
      // Explicitly non-goal for live backups; exists so tests can pin behavior.
      def += ` DEFAULT nextval('${c.column_name}_seq')`;
    }
  } else if (c.column_default) {
    def += ` DEFAULT ${c.column_default}`;
  }
  if (c.is_nullable === 'NO') def += ' NOT NULL';
  return def;
}
